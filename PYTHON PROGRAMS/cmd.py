# Monkey and Banana Problem

# Only one input
choice = input("Enter START to begin: ")

if choice.upper() == "START":

    print("Monkey is at Door")
    print("Monkey moves to Box")
    print("Monkey pushes Box under Banana")
    print("Monkey climbs the Box")
    print("Monkey picks the Banana")
    print("Goal Achieved!")

else:
    print("Program Stopped")